    fn payload(msg: &[u8; 9], frame_type: u8) -> Vec<u8> {
        let mut bits = Vec::with_capacity(PAYLOAD_BITS);
        for byte in msg {
            for shift in (0..8).rev() {
                bits.push((byte >> shift) & 1);
            }
        }
        for shift in (0..TYPE_BITS).rev() {
            bits.push((frame_type >> shift) & 1);
        }
        bits
    }

    #[test]
    fn matches_js8call_known_answers() {
        for (msg, frame_type, want) in VECTORS {
            let got = crc12(&payload(msg, *frame_type));
            assert_eq!(got, *want, "msg {msg:02x?} type {frame_type}");
        }
    }

    #[test]
    fn an_all_zero_payload_returns_the_final_xor_alone() {
        // The augmented remainder of all zeros is zero, so anything other than
        // 42 here means the XOR was dropped or applied twice.
        assert_eq!(crc12(&payload(&[0; 9], 0)), FINAL_XOR);
    }

    #[test]
    fn check_accepts_what_crc12_produced() {
        for (msg, frame_type, _) in VECTORS {
            let mut info = payload(msg, *frame_type);
            let crc = crc12(&info);
            info.resize(PAYLOAD_BITS + CRC_BITS, 0);
            place(&mut info, crc);
            assert!(check(&info), "msg {msg:02x?} type {frame_type}");
        }
    }

    #[test]
    fn check_rejects_a_single_flipped_payload_bit() {
        let mut info = payload(&VECTORS[0].0, VECTORS[0].1);
        let crc = crc12(&info);
        info.resize(PAYLOAD_BITS + CRC_BITS, 0);
        place(&mut info, crc);
        for i in 0..PAYLOAD_BITS {
            info[i] ^= 1;
            assert!(!check(&info), "flipping payload bit {i} went unnoticed");
            info[i] ^= 1;
        }
    }

    #[test]
    fn the_frame_type_is_covered_by_the_crc() {
        // The frame type rides in the CRC's byte 9, and an implementation that
        // forgot it would still pass every message-only test above.
        let crcs: Vec<u16> = (0..8).map(|t| crc12(&payload(&[0; 9], t))).collect();
        for (i, a) in crcs.iter().enumerate() {
            for b in &crcs[i + 1..] {
                assert_ne!(a, b, "two frame types share a CRC");
            }
        }
    }
