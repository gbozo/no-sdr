//! JS8's CRC-12 over the 75-bit payload.
//!
//! Two details here are load-bearing and neither is guessable:
//!
//! 1. It is an **augmented** CRC — the message bits shift straight into the
//!    register and the register is flushed by the trailing zero bits, rather
//!    than the more common form that XORs each byte into the top. JS8Call gets
//!    this from `boost::augmented_crc<12, 0xc06>` (`lib/crc12.cpp`).
//! 2. The result is **XORed with 42** (`lib/js8/genjs8.f90:48`). That has no
//!    counterpart in WSJT-X and no stated reason; the upstream comment is
//!    `TODO: jsherer - could change the crc here`. Omit it and every correct
//!    codeword fails verification, so the decoder finds signals, converges on
//!    them, and reports nothing at all.
//!
//! The known-answer vectors in the tests were produced by compiling JS8Call's
//! own `crc12.cpp` against boost, so they are outside-our-code evidence rather
//! than a restatement of what this file does.

/// Truncated CRC polynomial, `lib/crc12.cpp`.
const POLY: u16 = 0xc06;

/// Applied to the raw CRC before it goes on the wire, `lib/js8/genjs8.f90:48`.
const FINAL_XOR: u16 = 42;

const MASK: u16 = 0x0fff;

/// Bits of message payload ahead of the frame-type field.
pub const MSG_BITS: usize = 72;
/// Frame-type ("i3bit") field width.
pub const TYPE_BITS: usize = 3;
/// Payload guarded by the CRC.
pub const PAYLOAD_BITS: usize = MSG_BITS + TYPE_BITS;
/// Width of the CRC itself.
pub const CRC_BITS: usize = 12;

/// Boost's augmented CRC: message bits enter the register at the LSB, and the
/// polynomial is applied whenever a one leaves the top.
fn augmented(data: &[u8]) -> u16 {
    let mut rem: u16 = 0;
    for byte in data {
        for shift in (0..8).rev() {
            let bit = (byte >> shift) & 1;
            let top = rem & (1 << (CRC_BITS - 1)) != 0;
            rem = ((rem << 1) | u16::from(bit)) & MASK;
            if top {
                rem ^= POLY;
            }
        }
    }
    rem
}

/// CRC of a 75-bit payload: 72 message bits then 3 frame-type bits, each one
/// byte per element, MSB-first within the logical field.
///
/// The byte layout mirrors `lib/js8/genjs8.f90:41-47` exactly — nine bytes of
/// message, the frame type in the top three bits of the tenth, and an eleventh
/// zero byte that flushes the register.
pub fn crc12(payload: &[u8]) -> u16 {
    debug_assert_eq!(payload.len(), PAYLOAD_BITS);
    let mut buf = [0u8; 11];
    for (i, &bit) in payload.iter().take(MSG_BITS).enumerate() {
        if bit != 0 {
            buf[i >> 3] |= 0x80 >> (i & 7);
        }
    }
    let mut frame_type = 0u8;
    for &bit in &payload[MSG_BITS..PAYLOAD_BITS] {
        frame_type = (frame_type << 1) | (bit & 1);
    }
    buf[9] = (frame_type << 5) & 0b1110_0000;
    augmented(&buf) ^ FINAL_XOR
}

/// True when the trailing 12 bits of an 87-bit information word match a CRC
/// recomputed over the 75 that precede them.
///
/// This is the receive-side counterpart of [`crc12`] and is deliberately
/// symmetric with it. JS8Call's own `crc12_check` takes a different route —
/// it overwrites the frame-type byte with the CRC and re-runs the augmented
/// remainder — which does not round-trip against its own encoder for the
/// frame-type bits. Recomputing is unambiguous and matches what the encoder
/// actually transmitted.
pub fn check(info: &[u8]) -> bool {
    if info.len() < PAYLOAD_BITS + CRC_BITS {
        return false;
    }
    let mut got = 0u16;
    for &bit in &info[PAYLOAD_BITS..PAYLOAD_BITS + CRC_BITS] {
        got = (got << 1) | u16::from(bit & 1);
    }
    got == crc12(&info[..PAYLOAD_BITS])
}

/// Write a 12-bit CRC into `info[75..87]`, MSB-first.
pub fn place(info: &mut [u8], crc: u16) {
    for i in 0..CRC_BITS {
        info[PAYLOAD_BITS + i] = ((crc >> (CRC_BITS - 1 - i)) & 1) as u8;
    }
}

